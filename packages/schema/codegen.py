"""Generate ``ts/index.ts`` from the pydantic models (I-G5).

    uv run python codegen.py            # write ts/index.ts
    uv run python codegen.py --check    # exit 1 if the committed file is stale (CI)

The emitter covers the JSON Schema subset pydantic produces for these models:
objects, arrays, fixed tuples, enums / const, nullable and plain unions, ``$ref``.
Fields that have a default are optional in TS: a producer may leave them out, and a
consumer must accept that (I-G6, I-G7).
"""
from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any, get_args

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))

from pydantic import BaseModel  # noqa: E402
from pydantic.json_schema import models_json_schema  # noqa: E402

from schema import common, events, inventory, layout, reports, session, twin  # noqa: E402

MODULES = [common, twin, reports, inventory, layout, session, events]
OUT = HERE / "ts" / "index.ts"

# Literal aliases that get a named TS type.
ALIASES: dict[str, Any] = {
    # Read from the field annotations, so twin.py (Stream C) stays the only place they are written.
    "OpeningKind": twin.Opening.model_fields["kind"].annotation,
    "Glazing": twin.Opening.model_fields["glazing"].annotation,
    "TwinAlignment": twin.TwinQuality.model_fields["alignment"].annotation,
    "EventSource": events.EventSource,
    "ClientKind": events.ClientKind,
    "ViewerMode": events.ViewerMode,
    "JobStatus": events.JobStatus,
}

OCTAVE_BANDS_HZ = [63, 125, 250, 500, 1000, 2000, 4000, 8000]  # I-G14


def collect_models() -> list[type[BaseModel]]:
    seen: dict[str, type[BaseModel]] = {}
    for module in MODULES:
        for name, obj in vars(module).items():
            if (
                isinstance(obj, type)
                and issubclass(obj, BaseModel)
                and obj.__module__ == module.__name__
                and name != "Model"
            ):
                seen[name] = obj
    return list(seen.values())


def ts_type(node: dict[str, Any]) -> str:
    if "$ref" in node:
        return node["$ref"].rsplit("/", 1)[-1]
    if "const" in node:
        return json.dumps(node["const"])
    if "enum" in node:
        return " | ".join(json.dumps(v) for v in node["enum"])
    for key in ("anyOf", "oneOf"):
        if key in node:
            parts = [ts_type(n) for n in node[key]]
            return " | ".join(dict.fromkeys(parts))
    kind = node.get("type")
    if kind == "null":
        return "null"
    if kind in ("number", "integer"):
        return "number"
    if kind == "string":
        return "string"
    if kind == "boolean":
        return "boolean"
    if kind == "array":
        if "prefixItems" in node:
            return "[" + ", ".join(ts_type(n) for n in node["prefixItems"]) + "]"
        inner = ts_type(node.get("items", {}))
        return f"({inner})[]" if " | " in inner else f"{inner}[]"
    if kind == "object":
        if "properties" in node:
            return ts_object(node, indent="  ")
        extra = node.get("additionalProperties")
        value = ts_type(extra) if isinstance(extra, dict) else "unknown"
        return f"Record<string, {value}>"
    return "unknown"


def ts_object(node: dict[str, Any], indent: str = "") -> str:
    required = set(node.get("required", []))
    lines = ["{"]
    for name, prop in node.get("properties", {}).items():
        doc = prop.get("description")
        if doc:
            lines.append(f"{indent}  /** {doc} */")
        mark = "" if name in required else "?"
        lines.append(f"{indent}  {name}{mark}: {ts_type(prop)};")
    lines.append(indent + "}")
    return "\n".join(lines)


def render() -> str:
    _, top = models_json_schema(
        [(m, "validation") for m in collect_models()], ref_template="#/$defs/{model}"
    )
    defs: dict[str, Any] = top["$defs"]

    out: list[str] = [
        "// GENERATED by packages/schema/codegen.py from the pydantic models. Do not edit.",
        "// Regenerate: pnpm schema:codegen",
        "",
        f"export const EVENT_VERSION = {events.EVENT_VERSION} as const;",
        f"export const OCTAVE_BANDS_HZ = {json.dumps(OCTAVE_BANDS_HZ)} as const;",
        "",
    ]

    for name, literal in ALIASES.items():
        values = get_args(literal)
        out.append(f"export const {_const_name(name)} = {json.dumps(list(values))} as const;")
        out.append(f"export type {name} = (typeof {_const_name(name)})[number];")
        out.append("")

    for name in sorted(defs):
        node = defs[name]
        doc = node.get("description")
        if doc:
            body = "\n".join(f" * {line}".rstrip() for line in doc.strip().splitlines())
            out.append(f"/**\n{body}\n */")
        if node.get("type") == "object":
            out.append(f"export interface {name} {ts_object(node)}")
        else:
            out.append(f"export type {name} = {ts_type(node)};")
        out.append("")

    out.append("/** Event type -> payload type (section 2.3). */")
    out.append("export interface EventPayloads {")
    for event_type, model in events.EVENT_PAYLOADS.items():
        out.append(f"  {json.dumps(event_type)}: {model.__name__};")
    out.append("}")
    out.append("")
    out.append("export type EventType = keyof EventPayloads;")
    out.append(
        "export const EVENT_TYPES = "
        + json.dumps(list(events.EVENT_PAYLOADS))
        + " as const satisfies readonly EventType[];"
    )
    out.append("")
    out.append("/** The typed envelope for one known event type. */")
    out.append("export interface Event<T extends EventType = EventType> {")
    out.append("  v: number;")
    out.append("  id: string;")
    out.append("  ts: string;")
    out.append("  session_id: string;")
    out.append("  source: EventSource;")
    out.append("  type: T;")
    out.append("  payload: EventPayloads[T];")
    out.append("}")
    out.append("")
    out.append("/** Discriminated union of every known event. */")
    out.append("export type AnyEvent = { [T in EventType]: Event<T> }[EventType];")
    out.append("")
    out.append("/** Agent UI tool name -> the event it emits. */")
    out.append(
        "export const UI_TOOL_EVENTS = "
        + json.dumps(events.UI_TOOL_EVENTS, indent=2)
        + " as const satisfies Record<string, EventType>;"
    )
    out.append("")
    return "\n".join(out)


def _const_name(alias: str) -> str:
    snake = "".join("_" + c if c.isupper() else c for c in alias).lstrip("_").upper()
    return snake + ("ES" if snake.endswith("S") else "S")


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        current = OUT.read_text() if OUT.exists() else ""
        if current != text:
            print(f"{OUT.relative_to(HERE)} is stale. Run: pnpm schema:codegen", file=sys.stderr)
            return 1
        print("schema TS is up to date")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(HERE)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
